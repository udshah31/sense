"""Calibrates factscore_style_verdict's three thresholds
(configs/nli_judge.yaml's claim_supported_threshold, fraction_correct_threshold,
fraction_incorrect_threshold) against real human factuality labels, closing the
gap eval/README.md and docs/superpowers/specs/2026-08-16-nli-judge-design.md
name: "FActScore has no equivalent free known-right/known-wrong pair [like
HaluEval's right_answer/hallucinated_answer]; calibrating these needs either
real model generations judged by a human, or reused human annotations for
different models' outputs."

This takes the second route. The original FActScore paper (Min et al., 2023,
EMNLP) released real human annotations of 183 Wikipedia entities' biographies,
generated by three real commercial LLMs (InstructGPT, ChatGPT, PerplexityAI)
and hand-labeled sentence-by-sentence as Supported / Not-Supported / Irrelevant
by human annotators — see sense_data.factscore_labeled for provenance. This is
real ground truth from real (if not this project's own five-checkpoint) model
generations, judged by humans, not a self-entailment proxy the way the
short-answer calibration necessarily was (HaluEval has no such external
human-labeled release to reuse).

Two thresholds, two calibration sub-problems, run over the same topic-level
fit/holdout split:

1. claim_supported_threshold — direct ground truth exists at the individual
   atomic-fact level: every human-labeled fact carries S or NS (IR facts are
   excluded — "irrelevant to the prompt" isn't a support judgment). Sweep the
   entailment(reference_text, fact_text) threshold that best separates S from
   NS.
2. fraction_correct_threshold / fraction_incorrect_threshold — no direct label
   exists for "is this whole biography's supported_fraction high or low," but
   one is derived: human_supported_fraction = n_S / (n_S + n_NS) per example is
   FActScore's own actual per-example score, computed from real human labels.
   A biography is treated as unambiguously "good" ground truth when that
   fraction is >= GROUND_TRUTH_HIGH_FRACTION and "bad" when
   <= GROUND_TRUTH_LOW_FRACTION (examples in between are excluded as
   ambiguous ground truth, not swept against). This script's own
   supported_fraction (split_into_atomic_claims on the model's sentence-level
   granularity, not the human annotators' finer atomic decomposition, scored
   with the just-picked claim_supported_threshold) is then swept against that
   binarized ground truth.

Both sub-problems score each claim against its single best-matching
*reference sentence* (sense_eval.nli_judge.best_claim_entailment_batch), not
against the whole reference_text as one premise — the first version of this
script did the latter and it produced near-useless numbers (~52% claim-level
accuracy, worse than the ~70% majority-class baseline). Diagnosis: this small
NLI model (trained on MNLI's single-sentence premises) badly degrades against
a multi-paragraph premise even when it contains a sentence that plainly
supports the claim — see factscore_style_verdict's docstring for the
concrete example that proved it. Retrieval (lexical top-k pre-filter, then
NLI over just those candidate sentences) fixes this and matches real
FActScore's own methodology more closely besides.

Honest limitations, stated here and wherever this calibration's result is
cited (see sense_data.factscore_labeled's module docstring for the full
provenance/limitation list):
- Reference text is a 2026 Wikipedia snapshot, not the 2023-vintage text the
  original annotators verified against — the fixture drops any topic whose
  Wikipedia fetch failed or whose article may have drifted since.
- This project's own sentence-level claim splitter is coarser than the human
  annotators' atomic-fact decomposition, so the fraction-level calibration
  compares a coarser measurement against a finer-grained ground truth,
  not an apples-to-apples proxy.
- The retrieval step's lexical pre-filter (TOP_K_REFERENCE_SENTENCES
  candidates) can miss the true best-supporting sentence when it shares
  little vocabulary with the claim — a real, if smaller, source of error
  than scoring the whole document, not a fully solved retrieval problem.
- The generations judged are InstructGPT/ChatGPT/PerplexityAI (2023), not any
  of this project's five checkpoints — real progress over an arbitrary
  spot-check value, not a substitute for calibrating against this project's
  own model outputs.

Does not write configs/nli_judge.yaml itself — reports recommended values in
this run's result JSON for a human to review and apply deliberately, per
CLAUDE.md's "never add a default threshold value as a convenience fallback."
"""

import torch
import random

from _common import load_factscore_labeled_examples, load_yaml_config, write_results
from sense_eval.nli_judge import best_claim_entailment_batch, load_nli_model, split_into_atomic_claims

# A conservative multi-thread count (not left at torch's default, not capped
# to 1 either). Every premise scored by this script is now a single
# retrieved sentence, not a whole reference document — the giant, memory-
# hungry padded batches that forced a 1-thread cap in an earlier version of
# this script (see git history / results/factscore_threshold_calibration.json's
# first run) can't recur once premises are short, so some parallelism is
# safe again; kept modest since this machine is still only 8GB RAM.
torch.set_num_threads(4)

# Fine resolution near 0 (the first run's sweep hit 0.05 — the low end of the
# original 0.05-step-only range — with accuracy still rising as the threshold
# fell, a boundary optimum rather than a genuine interior peak; extended down
# to 0.0 with 0.01 steps below 0.1 to find where it actually turns).
CANDIDATE_THRESHOLDS = sorted(
    {round(0.01 * i, 2) for i in range(0, 11)} | {round(0.05 * i, 2) for i in range(1, 20)}
)  # 0.0, 0.01 .. 0.1, 0.15 .. 0.95
FIT_FRACTION = 0.8
SPLIT_SEED = 42

# What counts as unambiguous ground truth for the fraction-level calibration —
# matches the semantics fraction_correct_threshold/fraction_incorrect_threshold
# are meant to implement, not a value derived from this data.
GROUND_TRUTH_HIGH_FRACTION = 0.8
GROUND_TRUTH_LOW_FRACTION = 0.2


def load_config() -> dict:
    return {"nli_judge": load_yaml_config("nli_judge.yaml")}


def usable_topics(examples) -> list[str]:
    """Topics whose Wikipedia reference-text fetch succeeded — every example
    for a topic shares the same reference_text, so any one example's value
    tells us whether the topic is usable at all."""
    return sorted({e.topic for e in examples if e.reference_text is not None})


def split_fit_holdout(topics: list[str]) -> tuple[list[str], list[str]]:
    """Deterministic 80/20 split by topic (not by individual example) — a
    topic's examples across all 3 models share one reference_text, so
    splitting by example would leak that reference text across the fit/
    holdout boundary."""
    shuffled = list(topics)
    random.Random(SPLIT_SEED).shuffle(shuffled)
    n_fit = round(len(shuffled) * FIT_FRACTION)
    return sorted(shuffled[:n_fit]), sorted(shuffled[n_fit:])


def build_claim_cases(examples, topics: set) -> list[dict]:
    """One case per human-labeled S/NS atomic fact whose topic is in `topics`
    — IR facts are excluded (not a support judgment)."""
    cases = []
    for example in examples:
        if example.topic not in topics or example.reference_text is None:
            continue
        for fact in example.human_atomic_facts:
            if fact.label not in ("S", "NS"):
                continue
            cases.append(
                {
                    "topic": example.topic,
                    "model": example.model,
                    "fact_text": fact.text,
                    "label": fact.label,
                    "reference_text": example.reference_text,
                }
            )
    return cases


def compute_claim_entailment(model, tokenizer, claim_cases: list[dict]) -> list[dict]:
    """Precomputes each case's best-matching-reference-sentence entailment
    once — same retrieval `factscore_style_verdict` uses (see its
    docstring for why scoring against the whole reference_text at once
    doesn't work) — so sweeping candidate thresholds afterward needs no
    further model inference. `best_claim_entailment_batch` scores every
    case's candidate pairs in one batched pass across the whole
    `claim_cases` list, not per case — thousands of unbatched CPU forward
    passes is what made an earlier version of this script take nearly two
    hours."""
    items = [(case["fact_text"], split_into_atomic_claims(case["reference_text"])) for case in claim_cases]
    results = best_claim_entailment_batch(model, tokenizer, items)
    return [
        {**case, "entailment": score, "best_reference_sentence": sentence}
        for case, (score, sentence) in zip(claim_cases, results)
    ]


def accuracy_at_claim_threshold(cached_scores: list[dict], threshold: float) -> dict:
    """Binary classification accuracy: does entailment >= threshold correctly
    predict label == "S" (vs. "NS")? Also reports the two error directions
    separately since S/NS aren't perfectly balanced (~70/30 in this data) —
    a single accuracy number would hide whether errors skew toward false
    "supported" or false "not supported."""
    n_total = len(cached_scores)
    n_correct = 0
    n_s = n_ns = 0
    n_s_predicted_ns = 0  # false negative: truly supported, predicted not
    n_ns_predicted_s = 0  # false positive: truly not supported, predicted supported
    for row in cached_scores:
        predicted_s = row["entailment"] >= threshold
        actual_s = row["label"] == "S"
        n_correct += predicted_s == actual_s
        if actual_s:
            n_s += 1
            n_s_predicted_ns += not predicted_s
        else:
            n_ns += 1
            n_ns_predicted_s += predicted_s

    return {
        "threshold": threshold,
        "n_cases": n_total,
        "verdict_accuracy": n_correct / n_total,
        "false_negative_rate": (n_s_predicted_ns / n_s) if n_s else None,
        "false_positive_rate": (n_ns_predicted_s / n_ns) if n_ns else None,
    }


def sweep_claim_thresholds(cached_scores: list[dict], candidate_thresholds) -> list[dict]:
    return [accuracy_at_claim_threshold(cached_scores, threshold) for threshold in candidate_thresholds]


def pick_best_claim_threshold(sweep_results: list[dict]) -> dict:
    """Highest verdict_accuracy; ties broken by the lower threshold — deterministic."""
    return min(sweep_results, key=lambda r: (-r["verdict_accuracy"], r["threshold"]))


def human_supported_fraction(example) -> float | None:
    """FActScore's own real per-example score: n_S / (n_S + n_NS) over this
    example's human-labeled facts (IR excluded). None if there are no S/NS
    facts to compute a fraction from at all."""
    n_s = sum(1 for f in example.human_atomic_facts if f.label == "S")
    n_ns = sum(1 for f in example.human_atomic_facts if f.label == "NS")
    if n_s + n_ns == 0:
        return None
    return n_s / (n_s + n_ns)


def build_fraction_cases(model, tokenizer, examples, topics: set, claim_supported_threshold: float) -> list[dict]:
    """One case per example with a usable reference_text, a non-empty
    generation, and at least one human-labeled S/NS fact — pairs the real
    human_supported_fraction against this project's own supported_fraction
    (sentence-level claims, scored at the just-picked claim_supported_threshold).

    Two passes: first collect every eligible example's claims (no model
    calls yet), then score every claim's best-matching-reference-sentence
    pair across every example in one batched pass (best_claim_entailment_batch)
    — batching across examples, not just within one, is what actually
    avoids thousands of separate CPU forward passes here (see
    compute_claim_entailment's docstring for why that matters)."""
    pending = []
    for example in examples:
        if example.topic not in topics or example.reference_text is None:
            continue
        human_fraction = human_supported_fraction(example)
        if human_fraction is None:
            continue
        claims = split_into_atomic_claims(example.generated_text)
        if not claims:
            continue
        pending.append((example, human_fraction, claims))

    reference_sentences_by_example = {
        id(example): split_into_atomic_claims(example.reference_text) for example, _, _ in pending
    }
    all_items = [
        (claim, reference_sentences_by_example[id(example)])
        for example, _, claims in pending
        for claim in claims
    ]
    all_results = best_claim_entailment_batch(model, tokenizer, all_items)

    cases = []
    offset = 0
    for example, human_fraction, claims in pending:
        claim_results = all_results[offset : offset + len(claims)]
        offset += len(claims)
        n_supported = sum(1 for score, _ in claim_results if score >= claim_supported_threshold)
        cases.append(
            {
                "topic": example.topic,
                "model": example.model,
                "human_supported_fraction": human_fraction,
                "our_supported_fraction": n_supported / len(claims),
                "n_claims": len(claims),
            }
        )
    return cases


def _ground_truth_label(human_fraction: float) -> str:
    if human_fraction >= GROUND_TRUTH_HIGH_FRACTION:
        return "correct"
    if human_fraction <= GROUND_TRUTH_LOW_FRACTION:
        return "incorrect"
    return "ambiguous"


def accuracy_at_fraction_thresholds(
    cached_cases: list[dict], fraction_correct_threshold: float, fraction_incorrect_threshold: float
) -> dict:
    """Scores one candidate (fraction_correct_threshold, fraction_incorrect_threshold)
    pair against the binarized human ground truth, over only the cases with
    unambiguous ground truth (human_supported_fraction outside the
    (GROUND_TRUTH_LOW_FRACTION, GROUND_TRUTH_HIGH_FRACTION) band)."""
    n_definite = 0
    n_correct_verdict = 0
    n_unknown = 0
    for case in cached_cases:
        truth = _ground_truth_label(case["human_supported_fraction"])
        if truth == "ambiguous":
            continue
        n_definite += 1
        our_fraction = case["our_supported_fraction"]
        if our_fraction >= fraction_correct_threshold:
            predicted = "correct"
        elif our_fraction <= fraction_incorrect_threshold:
            predicted = "incorrect"
        else:
            predicted = "unknown"
        n_correct_verdict += predicted == truth
        n_unknown += predicted == "unknown"

    return {
        "fraction_correct_threshold": fraction_correct_threshold,
        "fraction_incorrect_threshold": fraction_incorrect_threshold,
        "n_definite_ground_truth_cases": n_definite,
        "verdict_accuracy": (n_correct_verdict / n_definite) if n_definite else None,
        "unknown_rate": (n_unknown / n_definite) if n_definite else None,
    }


def sweep_fraction_thresholds(cached_cases: list[dict], candidate_thresholds) -> list[dict]:
    """Every (correct, incorrect) pair with incorrect < correct — the only
    combinations that make semantic sense for the tri-state discretization."""
    return [
        accuracy_at_fraction_thresholds(cached_cases, correct_thr, incorrect_thr)
        for correct_thr in candidate_thresholds
        for incorrect_thr in candidate_thresholds
        if incorrect_thr < correct_thr
    ]


def pick_best_fraction_thresholds(sweep_results: list[dict]) -> dict:
    """Highest verdict_accuracy; ties broken by lower unknown_rate, then by
    the widest (correct - incorrect) gap (prefers a threshold pair that isn't
    balanced on a knife-edge), then deterministically by the threshold values."""
    return min(
        sweep_results,
        key=lambda r: (
            -r["verdict_accuracy"],
            r["unknown_rate"],
            -(r["fraction_correct_threshold"] - r["fraction_incorrect_threshold"]),
            r["fraction_correct_threshold"],
            r["fraction_incorrect_threshold"],
        ),
    )


def run() -> dict:
    config = load_config()
    model, tokenizer = load_nli_model(config["nli_judge"]["hf_repo"], config["nli_judge"]["revision"])

    examples = load_factscore_labeled_examples()
    topics = usable_topics(examples)
    fit_topics, holdout_topics = split_fit_holdout(topics)
    fit_topics_set, holdout_topics_set = set(fit_topics), set(holdout_topics)

    # --- claim_supported_threshold ---
    fit_claim_cases = compute_claim_entailment(model, tokenizer, build_claim_cases(examples, fit_topics_set))
    claim_sweep = sweep_claim_thresholds(fit_claim_cases, CANDIDATE_THRESHOLDS)
    best_claim = pick_best_claim_threshold(claim_sweep)

    holdout_claim_cases = compute_claim_entailment(model, tokenizer, build_claim_cases(examples, holdout_topics_set))
    holdout_claim_metrics = accuracy_at_claim_threshold(holdout_claim_cases, best_claim["threshold"])

    # --- fraction_correct_threshold / fraction_incorrect_threshold ---
    fit_fraction_cases = build_fraction_cases(model, tokenizer, examples, fit_topics_set, best_claim["threshold"])
    fraction_sweep = sweep_fraction_thresholds(fit_fraction_cases, CANDIDATE_THRESHOLDS)
    best_fraction = pick_best_fraction_thresholds(fraction_sweep)

    holdout_fraction_cases = build_fraction_cases(
        model, tokenizer, examples, holdout_topics_set, best_claim["threshold"]
    )
    holdout_fraction_metrics = accuracy_at_fraction_thresholds(
        holdout_fraction_cases,
        best_fraction["fraction_correct_threshold"],
        best_fraction["fraction_incorrect_threshold"],
    )

    return {
        "calibration_target": (
            "factscore_style_verdict's claim_supported_threshold, fraction_correct_threshold, "
            "fraction_incorrect_threshold (configs/nli_judge.yaml)"
        ),
        "hf_repo": config["nli_judge"]["hf_repo"],
        "revision": config["nli_judge"]["revision"],
        "ground_truth_source": (
            "FActScore paper's own released human annotations (Min et al., 2023) — "
            "InstructGPT/ChatGPT/PerplexityAI biographies of 183 Wikipedia entities, "
            "sentence-by-sentence S/NS/IR labels by human annotators. See "
            "sense_data.factscore_labeled module docstring for provenance."
        ),
        "n_topics_total": len(topics),
        "n_topics_fit": len(fit_topics),
        "n_topics_holdout": len(holdout_topics),
        "candidate_thresholds": CANDIDATE_THRESHOLDS,
        "claim_supported_threshold_fit_sweep": claim_sweep,
        "recommended_claim_supported_threshold": best_claim["threshold"],
        "recommended_claim_supported_threshold_fit_metrics": best_claim,
        "n_claim_fit_cases": len(fit_claim_cases),
        "n_claim_holdout_cases": len(holdout_claim_cases),
        "recommended_claim_supported_threshold_holdout_metrics": holdout_claim_metrics,
        "ground_truth_high_fraction": GROUND_TRUTH_HIGH_FRACTION,
        "ground_truth_low_fraction": GROUND_TRUTH_LOW_FRACTION,
        "fraction_thresholds_fit_sweep": fraction_sweep,
        "recommended_fraction_correct_threshold": best_fraction["fraction_correct_threshold"],
        "recommended_fraction_incorrect_threshold": best_fraction["fraction_incorrect_threshold"],
        "recommended_fraction_thresholds_fit_metrics": best_fraction,
        "n_fraction_fit_cases": len(fit_fraction_cases),
        "n_fraction_holdout_cases": len(holdout_fraction_cases),
        "recommended_fraction_thresholds_holdout_metrics": holdout_fraction_metrics,
        "method": (
            "claim_supported_threshold swept against direct human S/NS labels; "
            "fraction thresholds swept against human_supported_fraction (n_S/(n_S+n_NS)) "
            "binarized at ground_truth_high/low_fraction, using this project's own "
            "sentence-level supported_fraction as the predictor — see module docstring "
            "for the honest limitations of this proxy"
        ),
    }


def main() -> dict:
    result = run()
    write_results(
        "factscore_threshold_calibration.json",
        result,
        print_exclude_keys=frozenset({"claim_supported_threshold_fit_sweep", "fraction_thresholds_fit_sweep"}),
    )
    return result


if __name__ == "__main__":
    main()
